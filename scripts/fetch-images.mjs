/**
 * Downloads license-safe images listed in a manifest (JSON array) into src/assets/images/<id>.jpg,
 * resizes them to a sane maximum width with sharp, and regenerates src/content/images.ts
 * (static imports => next/image gets width/height/blurDataURL automatically) plus the credits list.
 *
 * Usage: node scripts/fetch-images.mjs path/to/imagery.json [--max=2400]
 * Manifest fields: id, tag, subject, source_page, download_url, author, license, license_url, orientation, use_for
 */
import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const manifestPath = process.argv[2];
if (!manifestPath) {
  console.error("Usage: node scripts/fetch-images.mjs <manifest.json> [--max=2400]");
  process.exit(1);
}
const maxWidth = Number((process.argv.find((a) => a.startsWith("--max=")) ?? "--max=2400").split("=")[1]);
const outDir = path.resolve("src/assets/images");
await fs.mkdir(outDir, { recursive: true });

const items = JSON.parse(await fs.readFile(manifestPath, "utf8"));
const ok = [];
for (const item of items) {
  const id = String(item.id).replace(/[^a-z0-9-]/gi, "-").toLowerCase();
  const target = path.join(outDir, `${id}.jpg`);
  try {
    let buf;
    try {
      buf = await fs.readFile(target);
      console.log(`skip (exists) ${id}`);
    } catch {
      const res = await fetch(item.download_url, { headers: { "user-agent": "Mozilla/5.0 (tajphotos image fetch)" } });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const raw = Buffer.from(await res.arrayBuffer());
      const meta = await sharp(raw).metadata();
      if (!meta.width || meta.width < 1200) throw new Error(`too small (${meta.width}px)`);
      buf = await sharp(raw)
        .rotate()
        .resize({ width: Math.min(meta.width, maxWidth), withoutEnlargement: true })
        .jpeg({ quality: 82, mozjpeg: true, progressive: true })
        .toBuffer();
      await fs.writeFile(target, buf);
      console.log(`saved ${id} (${meta.width}x${meta.height} -> ${(buf.length / 1024).toFixed(0)} KB)`);
    }
    const m = await sharp(buf).metadata();
    ok.push({ ...item, id, width: m.width, height: m.height });
  } catch (err) {
    console.warn(`FAILED ${id}: ${err.message}`);
  }
}

const esc = (s) => String(s ?? "").replace(/\\/g, "\\\\").replace(/"/g, '\\"');
const lines = [
  "// AUTO-GENERATED by scripts/fetch-images.mjs — do not edit by hand.",
  "// Static imports give next/image intrinsic width/height + blurDataURL at build time.",
  'import type { StaticImageData } from "next/image";',
  "",
  ...ok.map((i) => `import ${i.id.replace(/-/g, "_")} from "@/assets/images/${i.id}.jpg";`),
  "",
  "export interface SiteImage { src: StaticImageData; alt: string; credit: { author: string; source: string; license: string; licenseUrl: string; sourcePage: string }; subject: string; tags: string[]; useFor: string[]; }",
  "",
  "export const images = {",
  ...ok.map(
    (i) =>
      `  "${i.id}": { src: ${i.id.replace(/-/g, "_")}, alt: "${esc(i.alt ?? i.subject)}", subject: "${esc(i.subject)}", tags: ${JSON.stringify(String(i.tag ?? "").split(/[,\s]+/).filter(Boolean))}, useFor: ${JSON.stringify(String(i.use_for ?? "gallery").split(/[|,\s]+/).filter(Boolean))}, credit: { author: "${esc(i.author)}", source: "${esc(i.source ?? (i.source_page?.includes("unsplash") ? "Unsplash" : i.source_page?.includes("pexels") ? "Pexels" : i.source_page?.includes("wikimedia") ? "Wikimedia Commons" : i.source_page?.includes("pixabay") ? "Pixabay" : "Web"))}", license: "${esc(i.license)}", licenseUrl: "${esc(i.license_url)}", sourcePage: "${esc(i.source_page)}" } },`,
  ),
  "} satisfies Record<string, SiteImage>;",
  "",
  "export type ImageKey = keyof typeof images;",
  "export function getImage(id: string): SiteImage { const img = (images as Record<string, SiteImage>)[id]; if (!img) throw new Error(`Unknown image id: ${id}`); return img; }",
  "",
];
await fs.writeFile(path.resolve("src/content/images.ts"), lines.join("\n"));
console.log(`\nWrote src/content/images.ts with ${ok.length}/${items.length} images.`);
