/**
 * Generates src/content/{tours,destinations,guides}/index.ts by listing the directory,
 * so parallel content authors never touch a shared index file.
 * Usage: node scripts/gen-content-index.mjs
 */
import fs from "node:fs/promises";
import path from "node:path";

const collections = [
  { dir: "tours", type: "Tour", exportName: "tours" },
  { dir: "destinations", type: "Destination", exportName: "destinations" },
  { dir: "guides", type: "Guide", exportName: "guides" },
];

for (const c of collections) {
  const dir = path.resolve("src/content", c.dir);
  await fs.mkdir(dir, { recursive: true });
  const files = (await fs.readdir(dir)).filter((f) => f.endsWith(".ts") && f !== "index.ts").sort();
  const names = files.map((f, i) => ({ file: f.replace(/\.ts$/, ""), ident: `c${i}_${f.replace(/\.ts$/, "").replace(/[^a-zA-Z0-9]/g, "_")}` }));
  const out = [
    "// AUTO-GENERATED by scripts/gen-content-index.mjs — do not edit. Add a new file to this folder and re-run.",
    `import type { ${c.type} } from "@/content/types";`,
    ...names.map((n) => `import ${n.ident} from "./${n.file}";`),
    "",
    `export const ${c.exportName}: ${c.type}[] = [${names.map((n) => n.ident).join(", ")}];`,
    "",
  ].join("\n");
  await fs.writeFile(path.join(dir, "index.ts"), out);
  console.log(`${c.dir}: ${files.length} entries`);
}
